#!/usr/bin/env python3
"""Generate creative_tables.h from Creative's V0260Vid.inf (driver 1.11.02).

Every register value in the header comes from the INF; nothing is hand-tuned.
Usage: python3 gen_tables.py ../extracted-driver/V0260Vid.inf > creative_tables.h
"""
import re
import sys

inf = open(sys.argv[1], encoding="latin1").read()
# join "\"-continued lines, then drop ; comments
inf = re.sub(r"\\[ \t]*(;[^\n]*)?\n", "", inf)
lines = [l.split(";")[0].strip() for l in inf.splitlines()]

SEC = "%7670530"


def binval(section, sub, name):
    """Return [(reg, val, mask)] for HKR,<section>[\\sub],<name>,1,..."""
    key = SEC + section + "%" + ("\\" + sub if sub else "")
    for l in lines:
        parts = [p.strip() for p in l.split(",")]
        if len(parts) > 4 and parts[0] == "HKR" and parts[1] == key \
                and parts[2] == name and parts[3] == "1":
            v = [int(x, 16) for x in parts[4:] if x]
            assert len(v) % 3 == 0, (key, name, v)
            return [tuple(v[i:i + 3]) for i in range(0, len(v), 3)]
    raise KeyError((key, name))


def dword(section, name):
    key = SEC + section + "%"
    for l in lines:
        parts = [p.strip() for p in l.split(",")]
        if len(parts) > 4 and parts[0] == "HKR" and parts[1] == key \
                and parts[2] == name:
            return int(parts[4], 0)
    return None


out = []
w = out.append
w("/* Generated by gen_tables.py from Creative V0260Vid.inf 1.11.02")
w(" * (Live! Cam Vista IM VF0260, OV519 + OV7670). Do not edit. */")
w("")
w("struct cr_regmask { u8 reg, val, mask; };")
w("")


def table(name, rows):
    w("static const struct cr_regmask %s[] = {" % name)
    for r, v, m in rows:
        w("\t{ 0x%02x, 0x%02x, 0x%02x }," % (r, v, m))
    w("};")


def preset_tables(section, name, n, field="CamRegisters"):
    rows = [binval(section, "%04d" % i, field) for i in range(n)]
    width = len(rows[0])
    assert all(len(r) == width for r in rows), section
    w("static const struct cr_regmask %s[%d][%d] = {" % (name, n, width))
    for i, r in enumerate(rows):
        w("\t[%d] = {" % i + ", ".join(
            "{ 0x%02x, 0x%02x, 0x%02x }" % t for t in r) + " },")
    w("};")
    d = dword(section, "DefaultValue")
    w("#define %s_DEF %d" % (name.upper(), d if d is not None else 0))
    w("")


table("cr_init", binval("Set", None, "CameraSetting"))
w("")
table("cr_usb_init", binval("Set", None, "UsbSetting"))
w("")
preset_tables("Sat", "cr_sat", 7)
preset_tables("Shp", "cr_sharp", 10)
table("cr_sharp_auto_on", binval("Shp", None, "CamRegEnableAuto"))
table("cr_sharp_auto_off", binval("Shp", None, "CamRegDisableAuto"))
w("")
preset_tables("Gam", "cr_gamma", 5)
preset_tables("Wb", "cr_wb", 4)
preset_tables("BL", "cr_bl", 2)
preset_tables("Exp", "cr_exp", 16)
table("cr_exp_auto_on", binval("Exp", None, "CamRegEnableAuto"))
table("cr_exp_auto_off", binval("Exp", None, "CamRegDisableAuto"))
w("")
preset_tables("Gain", "cr_gain", 8)
print("\n".join(out))
